"""
load_logs.py — helpers to load simulator output CSVs into pandas DataFrames.

Usage:
    from load_logs import load_book_metrics, load_fills, load_pnl
    metrics = load_book_metrics("data/processed/run_20240405_120000")
"""

import pandas as pd
from pathlib import Path

TICK_MULTIPLIER = 100.0  # must match C++ TICK_MULTIPLIER


def _run_path(run_dir: str) -> Path:
    return Path(run_dir)


def load_book_metrics(run_dir: str) -> pd.DataFrame:
    """Load book_metrics.csv. Converts tick columns to float prices."""
    path = _run_path(run_dir) / "book_metrics.csv"
    df = pd.read_csv(path, dtype={
        "ts": "int64",
        "best_bid_ticks": "int64",
        "best_bid_qty": "int64",
        "best_ask_ticks": "int64",
        "best_ask_qty": "int64",
        "spread_ticks": "int64",
        "mid_ticks": "int64",
        "imbalance_5": "float64",
    })
    df["ts_us"] = df["ts"]
    df["ts"] = pd.to_datetime(df["ts"], unit="us", utc=True)
    df["best_bid"] = df["best_bid_ticks"] / TICK_MULTIPLIER
    df["best_ask"] = df["best_ask_ticks"] / TICK_MULTIPLIER
    df["spread"]   = df["spread_ticks"]   / TICK_MULTIPLIER
    df["mid"]      = df["mid_ticks"]      / TICK_MULTIPLIER
    return df


def load_fills(run_dir: str, only_filled: bool = False) -> pd.DataFrame:
    """Load fills.csv. Converts fill_price_ticks to float price.

    fills.csv is an execution-report log, not just fills: it also carries
    Cancelled and Rejected rows, which have fill_price == 0 (not a real
    price). Any price-based metric (slippage, markout, fill-price scatter)
    must exclude those or it'll be corrupted by (0 - mid) outliers — pass
    only_filled=True to get just the rows with status in
    {Filled, PartialFill}. Leave it False if you specifically want the raw
    execution-report log (e.g. to inspect cancellation patterns).
    """
    path = _run_path(run_dir) / "fills.csv"
    df = pd.read_csv(path, dtype={
        "ts": "int64",
        "order_id": "int64",
        "strategy_name": "str",
        "side": "str",
        "order_type": "str",
        "fill_price_ticks": "int64",
        "fill_qty": "int64",
        "fee": "float64",
        "status": "str",
    })
    df["ts_us"] = df["ts"]
    df["ts"] = pd.to_datetime(df["ts"], unit="us", utc=True)
    df["fill_price"] = df["fill_price_ticks"] / TICK_MULTIPLIER
    if only_filled:
        df = df[df["status"].isin(["Filled", "PartialFill"])].reset_index(drop=True)
    return df


def load_pnl(run_dir: str) -> pd.DataFrame:
    """Load pnl.csv.

    realized_pnl/unrealized_pnl/total_pnl are GROSS of fees — Portfolio only
    deducts fees from cash, never from realized PnL. fees_paid_cumulative and
    net_pnl (= total_pnl - fees_paid_cumulative) are what you actually want
    for "did this strategy make money." These two columns were added later —
    runs generated by an older build won't have them, so they're read as
    optional and back-filled as NaN rather than forcing a hard failure.
    """
    path = _run_path(run_dir) / "pnl.csv"
    df = pd.read_csv(path, dtype={
        "ts": "int64",
        "position": "int64",
        "cash": "float64",
        "realized_pnl": "float64",
        "unrealized_pnl": "float64",
        "mark_mid_ticks": "int64",
        "total_pnl": "float64",
    })
    for col in ("fees_paid_cumulative", "net_pnl"):
        if col not in df.columns:
            df[col] = float("nan")
        else:
            df[col] = df[col].astype("float64")
    df["ts_us"] = df["ts"]
    df["ts"] = pd.to_datetime(df["ts"], unit="us", utc=True)
    df["mark_mid"] = df["mark_mid_ticks"] / TICK_MULTIPLIER
    return df
